def test_card_layers_in_column_words():
    assert card_materials({
        "core": "сталь омеднённая посеребрённая витая", "dielectric": "ПТФЭ сплошной",
        "shield": "оплётка медь посеребрённая двойная", "jacket": "оболочка ФЭП",
    }) == {CORE: "сталь омеднённая посеребрённая", DIELECTRIC: "ПТФЭ", SHIELD: "медь посеребрённая, оплётка двойная",
           JACKET: "ФЭП"}


def test_card_beats_text_and_text_fills_what_the_card_has_not():
    fields = {"Жила: проволок × диаметр, мм": "1×0,91 (медь посеребрённая)", "Изоляция": "ПТФЭ (оболочка ПТФЭ)",
              "Экран": "проволочная оплетка из луженой меди"}
    # A semi-rigid card has no jacket layer: the jacket comes from the row's text.
    result = coax_materials(fields, {"core": "медь посеребрённая", "dielectric": "ФЭП", "shield": "трубка медная"})
    assert result == {CORE: ("медь посеребрённая", "карточка"), DIELECTRIC: ("ФЭП", "карточка"),
                      SHIELD: ("медь, трубка", "карточка"), JACKET: ("ПТФЭ", "Изоляция")}


def test_text_only_and_unknown_stays_out():
    result = coax_materials({"Жила: проволок × диаметр, мм": "1×2,7", "Изоляция": "ПЭ вспененный", "Экран": "оплётка 85%"})
    assert result == {DIELECTRIC: ("ПЭ вспененный", "Изоляция")}
