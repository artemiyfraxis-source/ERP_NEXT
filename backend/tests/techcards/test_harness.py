def test_предупреждения_вместо_молчаливых_умолчаний():
    """Молча подставленное умолчание в техкарте — это брак в цехе."""
    шаги, преды = построить(
        Сборка(
            wires=[Провод(name="без длины")],
            side_a=Разъём(name="A"),
        )
    )
    assert any("не задана длина" in p for p in преды)
    assert any("Сторона B" in p for p in преды)
    # Маршрут всё равно строится: человек решает, чинить описание или нет.
    assert шаги


def test_пустая_сборка_отвергается():
    шаги, преды = построить(Сборка())
    assert шаги == []
    assert преды and "нет проводов" in преды[0]


def test_позиции_идут_подряд():
    """Позиции — это порядок в карте: дырки в нумерации читаются как
    пропущенный шаг."""
    шаги, _ = построить(
        Сборка(
            wires=[Провод(name="а", length_mm=1), Провод(name="б", length_mm=2)],
            side_a=Разъём(name="A"),
            side_b=Разъём(name="B"),
            heatshrink=True,
            twist=True,
            marking=True,
        )
    )
    assert [ш.position for ш in шаги] == list(range(1, len(шаги) + 1))


def test_зависимости_не_ссылаются_вперёд():
    """Шаг не может ждать того, что идёт после него, — цех встанет."""
    шаги, _ = построить(
        Сборка(
            wires=[Провод(name="а", length_mm=1), Провод(name="б", length_mm=2)],
            side_a=Разъём(name="A"),
            side_b=Разъём(name="B"),
            heatshrink=True,
            twist=True,
            marking=True,
        )
    )
    for ш in шаги:
        for d in ш.depends_on:
            assert d < ш.position, f"шаг {ш.position} ждёт более поздний {d}"
