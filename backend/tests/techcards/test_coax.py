def test_смешанная_сборка_различает_стороны_в_наименовании():
    """Прямой и угловой разъём на одной сборке называются по-разному в
    один и тот же момент: угловой уже «разъём», прямой ещё «пин».

    Это и есть проверка того, что метка идёт от состояния сборки, а не
    от типа разъёма вообще. Рабочий по наименованию понимает, какой
    конец готов, а какой ждёт корпуса.
    """
    шаги, _ = построить_коакс(
        прямая(
            side_a=Сторона(article="SMA-male"),
            side_b=Сторона(article="SMA R/A", pin_type=ПИН_ВНУТРИ_КОРПУСА),
        )
    )
    # Момент после пайки обеих сторон, до монтажа корпуса прямой стороны.
    тут = next(ш for ш in шаги if ш.name.startswith("Монтаж термоусадки"))
    пайка_b = next(ш for ш in шаги if "контакта · сторона B" in ш.name)

    assert "Пин SMA-male" in пайка_b.semi_product, "сторона A ещё без корпуса"
    assert "разъём SMA R/A" in пайка_b.semi_product, "угловая сторона уже в корпусе"

    корпус = next(ш for ш in шаги if "Монтаж корпуса" in ш.name)
    assert корпус.semi_product.startswith("Разъём SMA-male"), (
        "после монтажа корпуса прямая сторона становится разъёмом"
    )
    assert тут.position < корпус.position


