def test_у_углового_разъёма_нет_монтажа_корпуса():
    """У R/A пин паяется уже внутри корпуса — монтировать нечего.
    Лишний шаг рабочий выполнить не сможет и встанет.

    Смешанная сборка (прямой + угловой) — единственный случай, где это
    различие видно по-настоящему: корпус монтируется ровно один раз, для
    прямой стороны. На двух угловых маршрут идёт другой веткой и
    ничего бы не доказал.
    """
    шаги, _ = построить_коакс(
        прямая(
            side_a=Сторона(article="SMA-male"),
            side_b=Сторона(
                article="SMA R/A", pin_type=ПИН_ВНУТРИ_КОРПУСА, cover=КРЫШКА_ВИНТ
            ),
        )
    )

    корпуса = [ш for ш in шаги if "Монтаж корпуса" in ш.name]
    assert len(корпуса) == 1, "корпус монтируется только прямому разъёму"
    assert "сторона A" in корпуса[0].name, "а сторона A здесь как раз прямая"


