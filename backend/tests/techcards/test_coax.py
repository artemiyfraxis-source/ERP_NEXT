# ── Порядок и связность ─────────────────────────────────────────────────────


def test_резка_первой_разделка_после_неё():
    """Пока кабель не отрезан, разделывать нечего.

    Как и с крышкой: проверяется зависимость, а не только порядок строк.
    Разделка, не ждущая резки, уйдёт в параллельную ветку планировщика.
    """
    шаги, _ = построить_коакс(прямая())
    резка = поз(шаги, "Резка кабеля")
    разделки = [ш for ш in шаги if ш.name.startswith("Разделка коаксиала")]

    assert разделки, "разделка должна быть"
    for ш in разделки:
        assert резка < ш.position
        assert резка in ш.depends_on, f"«{ш.name}» обязана ждать резку кабеля"


def test_тут_режется_параллельно_кабелю():
    """Термоусадка — отдельная заготовка: она не ждёт разделки и главный
    поток не трогает."""
    шаги, _ = построить_коакс(прямая())
    тут = next(ш for ш in шаги if ш.name.startswith("Резка термоусадки"))
    assert not тут.depends_on, "резка ТУТ ничего не ждёт"


def test_каждый_шаг_опирается_на_предыдущие():
    """Зависимость на шаг, который идёт позже, означала бы неисполнимый
    маршрут: планировщик зациклится, а рабочий не поймёт порядка."""
    шаги, _ = построить_коакс(прямая())
    for ш in шаги:
        for д in ш.depends_on:
            assert д < ш.position, f"«{ш.name}» опирается на более поздний шаг {д}"


