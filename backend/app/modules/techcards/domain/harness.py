"""Генератор маршрута кабельной сборки по её описанию.

Сейчас маршрут вбивают руками в каждый проект: пятнадцать строк операций,
одинаковых от сборки к сборке с точностью до количества проводов. Генератор
строит их из описания: сколько проводов, какие разъёмы на сторонах A и B,
есть ли термоусадка.

Логика перенесена из TcGenerator.gs (SUPPLYMAP), но без работы с
Google-таблицами — там на неё уходит половина файла. Взято ядро: порядок
операций, связка «выход предыдущей = вход следующей» и нормы.

Что заложено в порядок и почему он именно такой:

  · РЕЗКА ПЕРВОЙ. Пока провода не нарезаны, делать нечего.

  · ТЕРМОУСАДКА НАДЕВАЕТСЯ ДО ОПРЕССОВКИ. После — уже не наденется:
    наконечник не проходит внутрь трубки. Это самая частая ошибка новичка
    и главная причина, по которой порядок операций держат в системе, а не
    в голове.

  · СТОРОНЫ A И B ИДУТ ПАРАЛЛЕЛЬНО. Опрессовка стороны B не ждёт монтажа
    стороны A — это разные концы одного провода. У них это отдельная
    ветка кода с состоянием по сторонам; здесь то же самое выражено
    зависимостями операций.

  · ОТК И УПАКОВКА ЗАМЫКАЮТ. Проверяют собранное изделие, а не
    полуфабрикат.

Что НЕ переносим: подбор аппликатора по сечению провода, диаграммы
разделки коаксиала, шаблоны листов. Это отдельная предметная область с
таблицами соответствий, которых у нас нет.
"""

from dataclasses import dataclass, field


@dataclass
class Провод:
    """Провод сборки: марка, длина, сколько таких в изделии."""

    name: str = ""
    length_mm: float = 0.0
    qty: float = 1.0
    # Разделка: снять изоляцию с концов. Нужна под опрессовку и пайку.
    strip: bool = True


@dataclass
class Разъём:
    """Разъём на конце сборки."""

    name: str = ""
    # Сколько контактов заводится: по нему считается норма опрессовки.
    contacts: float = 1.0
    # Опрессовка (наконечники) или пайка. Разные операции и разное время.
    solder: bool = False


@dataclass
class Сборка:
    """Описание кабельной сборки — вход генератора."""

    name: str = ""
    wires: list[Провод] = field(default_factory=list)
    side_a: Разъём | None = None
    side_b: Разъём | None = None
    # Термоусадка на концах: отдельная заготовка, которая надевается ДО
    # опрессовки.
    heatshrink: bool = False
    # Скрутка пар: делается после резки, до разделки.
    twist: bool = False
    # Маркировка проводов.
    marking: bool = False


@dataclass
class ШагМаршрута:
    """Операция маршрута — то, что уйдёт в расчёт и в цех."""

    position: int
    code: str
    name: str
    component: str | None = None
    # Полуфабрикат: по нему операции группируются, а разные полуфабрикаты
    # идут параллельно.
    semi_product: str | None = None
    # Множитель нормы: у опрессовки норматив на контакт, а не на изделие.
    count: float = 1.0
    length_m: float = 0.0
    requirement: str | None = None
    # На какие шаги опирается (позиции). Пусто — можно начинать сразу.
    depends_on: list[int] = field(default_factory=list)


# Коды операций справочника. Если кода нет в базе технолога, маршрут всё
# равно строится: сметчик увидит его в списке ненайденных и заведёт.
КОД_РЕЗКА = "CUT_WIRE"
КОД_РЕЗКА_РАЗДЕЛКА = "CUT_WIRE+1STRIP"
КОД_СКРУТКА = "TWIST"
КОД_МАРКИРОВКА = "MARK"
КОД_РЕЗКА_ТУТ = "CUT_TUT"
КОД_МОНТАЖ_ТУТ = "INS_TUT"
КОД_ОПРЕССОВКА = "PRS_TERMINAL_AUTO"
КОД_ПАЙКА = "SDR_TIN"
КОД_МОНТАЖ = "INS_TERMINAL"
КОД_ОТК = "OTK_AUTO"
КОД_УПАКОВКА = "BOX"


def построить(сборка: Сборка) -> tuple[list[ШагМаршрута], list[str]]:
    """Описание сборки → маршрут операций.

    Возвращает шаги и предупреждения: то, что генератор решил за человека
    и о чём он должен знать. Молча подставленное умолчание в техкарте —
    это брак в цехе.
    """
    предупреждения: list[str] = []
    if not сборка.wires:
        return [], ["В сборке нет проводов — маршрут строить не из чего"]

    шаги: list[ШагМаршрута] = []
    поз = 0

    def добавить(**kw) -> ШагМаршрута:
        nonlocal поз
        поз += 1
        шаг = ШагМаршрута(position=поз, **kw)
        шаги.append(шаг)
        return шаг

    # ── 1. Резка проводов ───────────────────────────────────────────────
    #
    # Каждый провод своей строкой: у них разная длина, и объединять их в
    # одну операцию значит потерять допуск — карта покажет контрольную
    # длину первого провода для всех. Мы этот дефект у них и нашли.
    резка: list[int] = []
    for провод in сборка.wires:
        код = КОД_РЕЗКА_РАЗДЕЛКА if провод.strip else КОД_РЕЗКА
        имя = провод.name or "провод"
        ш = добавить(
            code=код,
            name="Резка с разделкой" if провод.strip else "Резка",
            component=имя,
            semi_product=имя,
            count=провод.qty,
            length_m=round((провод.length_mm or 0.0) / 1000.0, 4),
            requirement=(
                f"Длина {провод.length_mm:g} мм"
                if провод.length_mm
                else "Длина не задана — уточнить у технолога"
            ),
        )
        резка.append(ш.position)
        if not провод.length_mm:
            предупреждения.append(f"{имя}: не задана длина")

    # ── 2. Скрутка ──────────────────────────────────────────────────────
    # Хвост цепочки по каждому проводу: на что опирается следующая операция
    # над ним. Обновляется по мере добавления общих шагов (скрутка, маркировка).
    хвост_по_проводу = dict(enumerate(резка))

    if сборка.twist:
        ш = добавить(
            code=КОД_СКРУТКА,
            name="Скрутка пар",
            requirement="Шаг скрутки — по чертежу",
            depends_on=list(резка),
        )
        for индекс in хвост_по_проводу:
            хвост_по_проводу[индекс] = ш.position

    if сборка.marking:
        ш = добавить(
            code=КОД_МАРКИРОВКА,
            name="Маркировка проводов",
            count=sum(п.qty for п in сборка.wires),
            depends_on=sorted(set(хвост_по_проводу.values())),
        )
        for индекс in хвост_по_проводу:
            хвост_по_проводу[индекс] = ш.position

    # ── 3. Термоусадка ──────────────────────────────────────────────────
    #
    # Отдельная заготовка: режется параллельно проводам и надевается ДО
    # опрессовки. После опрессовки трубка уже не наденется — наконечник не
    # проходит внутрь.
    тут_готов: int | None = None
    if сборка.heatshrink:
        резка_тут = добавить(
            code=КОД_РЕЗКА_ТУТ,
            name="Резка термоусадки",
            semi_product="термоусадка",
            count=sum(п.qty for п in сборка.wires) * 2,
            requirement="Длина трубки — по чертежу",
        )
        монтаж_тут = добавить(
            code=КОД_МОНТАЖ_ТУТ,
            name="Надеть термоусадку",
            semi_product="термоусадка",
            count=sum(п.qty for п in сборка.wires) * 2,
            requirement="ДО опрессовки: после наконечник не пройдёт в трубку",
            depends_on=[резка_тут.position] + sorted(set(хвост_по_проводу.values())),
        )
        тут_готов = монтаж_тут.position

    # ── 4. Стороны A и B ────────────────────────────────────────────────
    #
    # Параллельно: опрессовка стороны B не ждёт монтажа стороны A — это
    # разные концы одного провода.
    вход = [тут_готов] if тут_готов else sorted(set(хвост_по_проводу.values()))
    концы: list[int] = []

    for метка, разъём in (("A", сборка.side_a), ("B", сборка.side_b)):
        if разъём is None:
            предупреждения.append(f"Сторона {метка}: разъём не задан")
            continue
        контактов = разъём.contacts or 1.0
        крепёж = добавить(
            code=КОД_ПАЙКА if разъём.solder else КОД_ОПРЕССОВКА,
            name=("Пайка контактов" if разъём.solder else "Опрессовка контактов")
            + f" · сторона {метка}",
            component=разъём.name or None,
            semi_product=f"сторона {метка}",
            # Норматив на контакт: сколько контактов — столько работы.
            count=контактов,
            depends_on=list(вход),
        )
        монтаж = добавить(
            code=КОД_МОНТАЖ,
            name=f"Монтаж разъёма · сторона {метка}",
            component=разъём.name or None,
            semi_product=f"сторона {метка}",
            count=контактов,
            requirement="Проверить порядок контактов по чертежу",
            depends_on=[крепёж.position],
        )
        концы.append(монтаж.position)

    if not концы:
        предупреждения.append("Ни одна сторона не задана — маршрут обрывается на резке")
        концы = вход

    # ── 5. Контроль и упаковка ──────────────────────────────────────────
    #
    # Проверяют собранное изделие, поэтому ждут ОБЕ стороны.
    отк = добавить(
        code=КОД_ОТК,
        name="ОТК: прозвонка",
        requirement="Прозвонить все цепи, проверить отсутствие КЗ",
        depends_on=list(концы),
    )
    добавить(
        code=КОД_УПАКОВКА,
        name="Упаковка",
        depends_on=[отк.position],
    )

    return шаги, предупреждения
