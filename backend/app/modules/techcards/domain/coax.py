"""Маршрут коаксиальной сборки.

Коаксиальная сборка собирается иначе, чем обычный жгут, и её маршрут
нельзя получить из общего генератора добавлением пары операций. Разница
в том, что у коаксиала концентрическая конструкция: центральная жила,
диэлектрик, экран, оболочка. Каждый слой разделывается на свою длину, и
почти каждая операция что-то надевает на кабель — а надеть можно только
пока конец открыт.

Логика перенесена из SUPPLYMAP: TcCoax.gs (наименования результатов и
топология жгута) и коакс-ветка getActiveOpsCoax_ из TcGeneratorUi.html
(порядок операций). Там она размазана между сервером и формой; здесь
собрана в одном месте, потому что это предметное знание, а не вёрстка.

Модуль ничего не знает ни о базе данных, ни о вебе: на входе описание
сборки, на выходе список шагов. Так его можно проверить тестами без
поднятия приложения — а порядок операций здесь именно то, что стоит
проверять, потому что ошибка в нём видна только в цехе.

Три правила, ради которых генератор вообще нужен — нарушение каждого
даёт брак, который виден только на сборке:

  · ТУТ И ВТУЛКА НАДЕВАЮТСЯ, ПОКА КОНЕЦ ОТКРЫТ. Если оба разъёма
    угловые («пайка внутри корпуса»), трубку надевают МЕЖДУ пайкой
    стороны A и пайкой стороны B: через уже запаянный разъём она не
    пройдёт, а второй конец к тому моменту ещё свободен. При прямых
    разъёмах такой спешки нет — корпус монтируется отдельной операцией
    позже, и трубку можно надеть после обеих паек.

  · ВТУЛКА ЭКРАНА НУЖНА ТОЛЬКО ПОД ОБЖИМ. При паяном экране ферулы нет
    вообще: экран припаивается к корпусу разъёма напрямую. Лишняя
    втулка в карте — это лишняя позиция в закупке и операция, которую
    рабочий не сможет выполнить.

  · КРЫШКА УГЛОВОГО РАЗЪЁМА — ПОСЛЕ УСАДКИ ТУТ. Крышка закрывает узел
    целиком; если поставить её раньше, до трубки уже не добраться.

Что НЕ переносим: подбор записи из БД.КОАКС по артикулу (D1–D3, L1–L3 —
размеры разделки). Это справочник, которого в ERP пока нет; когда
появится, длины разделки встанут в requirement вместо «по чертежу».
Отмечено в ТЗ на остаток.
"""

from dataclasses import dataclass, field

from .harness import ШагМаршрута

# ── Типы исполнения ─────────────────────────────────────────────────────────

# Пин паяется внутри корпуса — угловой разъём (R/A). Корпус уже надет на
# кабель к моменту пайки, поэтому отдельной операции монтажа корпуса нет,
# зато появляется крышка.
ПИН_ВНУТРИ_КОРПУСА = "внутри корпуса"
ПИН_ПАЙКА = "пайка"
# Цанговый центральный контакт («центральный контакт - цанговый и не требует пайки»): пин не паяется, он садится на жилу
# при монтаже корпуса — как в генераторе (`COAX_PIN_COLLET`, владелец 16.10).
ПИН_ЦАНГА = "цанга"

ЭКРАН_ОБЖИМ = "обжим"
ЭКРАН_ПАЙКА = "пайка"

КРЫШКА_ОБЖИМ = "обжим"
КРЫШКА_ВИНТ = "винт"


# ── Коды операций ───────────────────────────────────────────────────────────
#
# Коды справочника технолога. Как и в общем генераторе: если кода нет в
# базе, маршрут всё равно строится, а ненайденный код показывается
# сметчику.
КОД_РЕЗКА_КАБЕЛЯ = "CUT_COAX_auto"  # своя карта резки коаксиала (владелец 16.10), не карта провода
КОД_РЕЗКА_ТУТ = "CUT_TUT_short"
КОД_РАЗДЕЛКА = "STRIP_COAX_auto"
КОД_ПАЙКА_ПИНА = "SDR_COAX_pin"
КОД_ПАЙКА_ПИНА_УГЛОВОЙ = "SDR_COAX_pin_R/A"
КОД_МОНТАЖ_ТУТ = "INS_TUT"
КОД_МОНТАЖ_ВТУЛКИ = "INS_SLEEVE_coax"
КОД_МОНТАЖ_КОРПУСА = "INS_housing_COAX"
КОД_ПАЙКА_ЭКРАНА = "SDR_COAX_housing"
КОД_ОПРЕССОВКА_ВТУЛКИ = "PRS_SLEEVE_coax"
КОД_УСАДКА = "HEAT_TYT_short"
КОД_КРЫШКА_ОБЖИМ = "PRS_CAP"
КОД_КРЫШКА_ВИНТ = "INS_CAP"


@dataclass
class Сторона:
    """Конец коаксиальной сборки: разъём и способ его посадки."""

    article: str = ""
    name: str = ""
    # «пайка» — прямой разъём, корпус монтируется отдельной операцией.
    # «внутри корпуса» — угловой (R/A): пин паяется уже в корпусе.
    pin_type: str = ПИН_ПАЙКА
    # Крышка бывает только у углового разъёма: «обжим» | «винт» | «».
    cover: str = ""

    @property
    def угловой(self) -> bool:
        return self.pin_type == ПИН_ВНУТРИ_КОРПУСА

    @property
    def цанга(self) -> bool:
        return self.pin_type == ПИН_ЦАНГА

    @property
    def ссылка(self) -> str:
        """Как называть разъём в карте: артикул, иначе имя из состава."""
        return self.article or self.name or "разъём"


@dataclass
class КоаксСборка:
    """Описание коаксиальной сборки — вход генератора."""

    cable_article: str = ""
    cable_name: str = ""
    cable_length_mm: float = 0.0
    # Сторона A есть всегда: без неё это не сборка, а отрезок кабеля.
    side_a: Сторона | None = None
    # Односторонняя сборка — обычное дело (пигтейл), сторона B пустая.
    side_b: Сторона | None = None
    shield_type: str = ЭКРАН_ОБЖИМ
    tut_article: str = ""
    tut_name: str = ""
    # Типовой отрезок термоусадки на коакс-разъём — 20 мм.
    tut_length_mm: float = 20.0
    # Односторонняя сборка со снятой изоляцией на свободном конце:
    # голый конец под пайку на плату. Только когда стороны B нет.
    strip_free_end: bool = False


# ── Наименования полуфабрикатов ─────────────────────────────────────────────
#
# Порт computeCoaxResult_/coaxHarness_ из TcCoax.gs. Наименование
# результата — это то, что рабочий видит как «что у меня в руках после
# этой операции». Оно накопительное: выход предыдущей операции становится
# входом следующей, и по нему собирается топология жгута.


def _ссылка_на_кабель(с: КоаксСборка) -> str:
    """«LMR-100 600мм» — кабель с длиной, если длина задана."""
    кабель = с.cable_article or с.cable_name or "кабель"
    return f"{кабель} {с.cable_length_mm:g}мм" if с.cable_length_mm else кабель


def _метка_стороны(
    сторона: Сторона | None, запаяна: bool, в_корпусе: bool
) -> str | None:
    """Как называется конец на данном этапе сборки.

    Пока пин не впаян, сторона в топологии не фигурирует вообще. После
    пайки прямой разъём — это «пин» (торчит центральный контакт), и
    только после монтажа корпуса он становится «разъёмом».

    У углового корпус надет с самого начала, поэтому «разъёмом» он
    становится сразу при пайке — но выражено это не здесь, а через
    состояние: пайка углового сама выставляет «в корпусе». Проверять
    тут ещё и `сторона.угловой` значило бы держать одно правило в двух
    местах, которые рано или поздно разойдутся.
    """
    if сторона is None or not запаяна:
        return None
    return "разъём" if в_корпусе else "пин"


@dataclass
class _Состояние:
    """Что уже сделано по сторонам — от этого зависит наименование."""

    запаяна: dict = field(default_factory=lambda: {"A": False, "B": False})
    в_корпусе: dict = field(default_factory=lambda: {"A": False, "B": False})


def _топология(с: КоаксСборка, сост: _Состояние) -> str:
    """«Пин SMA-male — кабель LMR-100 600мм — разъём N-female».

    Единая база наименований всех сборочных операций после пайки: к ней
    дописывается, что именно сделали. Однотипность здесь не косметика —
    рабочий по этой строке сверяет, ту ли деталь держит.
    """
    кабель = _ссылка_на_кабель(с)
    метка_a = _метка_стороны(с.side_a, сост.запаяна["A"], сост.в_корпусе["A"])
    метка_b = _метка_стороны(с.side_b, сост.запаяна["B"], сост.в_корпусе["B"])

    if метка_a:
        текст = f"{метка_a.capitalize()} {с.side_a.ссылка} — кабель {кабель}"
    else:
        текст = f"Кабель {кабель}"
    if метка_b:
        текст += f" — {метка_b} {с.side_b.ссылка}"
    return текст


# ── Построение маршрута ─────────────────────────────────────────────────────


def построить_коакс(с: КоаксСборка) -> tuple[list[ШагМаршрута], list[str]]:
    """Описание коаксиальной сборки → маршрут операций.

    Возвращает шаги и предупреждения. Предупреждение — это то, что
    генератор решил за человека: молча подставленное умолчание в
    техкарте оборачивается браком в цехе.
    """
    предупреждения: list[str] = []
    if с.side_a is None:
        return [], ["Сторона A не задана — это отрезок кабеля, а не сборка"]

    двусторонняя = с.side_b is not None
    # Число концов: по нему считается время операций, которые делаются
    # «за один раз на оба конца» (ТУТ, втулка, усадка).
    концов = 2 if двусторонняя else 1
    сост = _Состояние()

    шаги: list[ШагМаршрута] = []
    поз = 0

    def добавить(**kw) -> ШагМаршрута:
        nonlocal поз
        поз += 1
        шаг = ШагМаршрута(position=поз, **kw)
        шаги.append(шаг)
        return шаг

    if not с.cable_length_mm:
        предупреждения.append("Не задана длина кабеля")

    # ── 1. Заготовки: кабель и термоусадка ──────────────────────────────
    #
    # ТУТ режется параллельно кабелю: это отдельная заготовка, главный
    # поток она не трогает.
    кабель = добавить(
        code=КОД_РЕЗКА_КАБЕЛЯ,
        name="Резка кабеля",
        component=с.cable_article or с.cable_name or None,
        semi_product=_ссылка_на_кабель(с),
        length_m=round((с.cable_length_mm or 0.0) / 1000.0, 4),
        requirement=(
            f"Длина {с.cable_length_mm:g} мм"
            if с.cable_length_mm
            else "Длина не задана — уточнить у технолога"
        ),
    )
    тут = добавить(
        code=КОД_РЕЗКА_ТУТ,
        name="Резка термоусадки" + (f" ×{концов}" if концов > 1 else ""),
        component=с.tut_article or с.tut_name or None,
        semi_product="термоусадка",
        count=концов,
        requirement=f"Длина трубки {с.tut_length_mm:g} мм",
    )

    # ── 2. Разделка концов ──────────────────────────────────────────────
    #
    # Снять оболочку, отвернуть экран, оголить центральную жилу — каждый
    # слой на свою длину. Длины берутся из БД.КОАКС по артикулу разъёма;
    # справочника у нас пока нет, поэтому отсылка к чертежу.
    разделки: list[int] = []
    for метка, сторона in (("A", с.side_a), ("B", с.side_b)):
        if сторона is None:
            continue
        ш = добавить(
            code=КОД_РАЗДЕЛКА,
            name=f"Разделка коаксиала · сторона {метка}",
            component=сторона.ссылка,
            semi_product=f"Разделка {метка} под {сторона.ссылка}"
            f" на кабеле: {с.cable_article or с.cable_name or 'кабель'}",
            requirement="Длины разделки D1–D3 / L1–L3 — по чертежу разъёма",
            depends_on=[кабель.position],
        )
        разделки.append(ш.position)

    # Односторонняя сборка с голым концом: свободный конец зачищается под
    # пайку на плату. Стороны B при этом нет — операция без разъёма.
    if с.strip_free_end and not двусторонняя:
        ш = добавить(
            code=КОД_РАЗДЕЛКА,
            name="Зачистка стороны B · голый конец",
            semi_product="Свободный конец кабеля зачищен",
            requirement="Оголить жилу и экран под пайку на плату",
            depends_on=[кабель.position],
        )
        разделки.append(ш.position)
    elif с.strip_free_end and двусторонняя:
        предупреждения.append(
            "Зачистка голого конца задана, но сторона B занята разъёмом — пропущена"
        )

    # ── 3. Пайка пинов, ТУТ и втулка ────────────────────────────────────
    #
    # Здесь главная развилка. Втулка экрана (ферул) существует только
    # при обжимном экране: при паяном экран идёт прямо на корпус.
    есть_втулка = с.shield_type == ЭКРАН_ОБЖИМ
    оба_угловых = (
        двусторонняя and с.side_a.угловой and с.side_b is not None and с.side_b.угловой
    )

    def пайка_пина(метка: str, сторона: Сторона, зависит: list[int]) -> ШагМаршрута:
        сост.запаяна[метка] = True
        if сторона.угловой:
            # У углового корпус уже на кабеле — пин паяется внутри него.
            сост.в_корпусе[метка] = True
        return добавить(
            code=КОД_ПАЙКА_ПИНА_УГЛОВОЙ if сторона.угловой else КОД_ПАЙКА_ПИНА,
            name=f"Пайка центрального контакта · сторона {метка}",
            component=сторона.ссылка,
            semi_product=_топология(с, сост),
            depends_on=зависит,
            requirement="Не перегреть диэлектрик: оплавление меняет волновое "
            "сопротивление",
        )

    def монтаж_тут(зависит: list[int]) -> ШагМаршрута:
        return добавить(
            code=КОД_МОНТАЖ_ТУТ,
            name="Монтаж термоусадки" + (f" ×{концов}" if концов > 1 else ""),
            component=с.tut_article or с.tut_name or None,
            semi_product=f"Кабель {_ссылка_на_кабель(с)} с надетыми ТУТ",
            count=концов,
            depends_on=зависит,
        )

    def монтаж_втулки(зависит: list[int]) -> ШагМаршрута:
        return добавить(
            code=КОД_МОНТАЖ_ВТУЛКИ,
            name="Монтаж втулки экрана" + (f" ×{концов}" if концов > 1 else ""),
            semi_product=f"Кабель {_ссылка_на_кабель(с)} с надетыми гильзами",
            count=концов,
            depends_on=зависит,
        )

    концы: list[int] = []

    if оба_угловых:
        # Оба разъёма угловые: надеть ТУТ и втулку МЕЖДУ паек. Через
        # запаянный угловой разъём трубка не проходит, а второй конец в
        # этот момент ещё открыт — это единственное окно.
        пайка_a = пайка_пина("A", с.side_a, list(разделки) + [тут.position])
        хвост = [пайка_a.position]
        ш_тут = монтаж_тут(хвост)
        хвост = [ш_тут.position]
        if есть_втулка:
            хвост = [монтаж_втулки(хвост).position]
        пайка_b = пайка_пина("B", с.side_b, хвост)
        концы = [пайка_b.position]
        предупреждения.append(
            "Оба разъёма угловые: термоусадка и втулка надеваются между "
            "пайкой сторон A и B — после пайки обеих сторон их уже не надеть"
        )
    else:
        пайки: list[int] = []
        for метка, сторона in (("A", с.side_a), ("B", с.side_b)):
            if сторона is not None and not сторона.цанга:  # цанговый пин не паяется
                пайки.append(пайка_пина(метка, сторона, list(разделки) + [тут.position]).position)

        хвост = [монтаж_тут(пайки or list(разделки) + [тут.position]).position]
        if есть_втулка:
            хвост = [монтаж_втулки(хвост).position]

        # Корпус монтируется только у прямого разъёма: у углового пин
        # паяется уже внутри корпуса, отдельной операции нет.
        корпуса: list[int] = []
        for метка, сторона in (("A", с.side_a), ("B", с.side_b)):
            if сторона is None or сторона.угловой:
                continue
            сост.в_корпусе[метка] = True
            сост.запаяна[метка] = True  # цанговый пин садится здесь же — с этого шага конец «разъём»
            корпуса.append(
                добавить(
                    code=КОД_МОНТАЖ_КОРПУСА,
                    name=f"Монтаж корпуса · сторона {метка}" + (" — цанговый контакт, без пайки" if сторона.цанга else ""),
                    component=сторона.ссылка,
                    semi_product=f"{_топология(с, сост)} (корпус смонтирован, ст. {метка})",
                    depends_on=list(хвост),
                ).position
            )
        концы = корпуса or хвост

    # ── 4. Экран ────────────────────────────────────────────────────────
    #
    # Паяный — по сторонам, на корпус каждого разъёма. Обжимной — одна
    # операция на сборку: опрессовывается та самая втулка.
    if с.shield_type == ЭКРАН_ПАЙКА:
        экран: list[int] = []
        for метка, сторона in (("A", с.side_a), ("B", с.side_b)):
            if сторона is None:
                continue
            экран.append(
                добавить(
                    code=КОД_ПАЙКА_ЭКРАНА,
                    name=f"Пайка экрана · сторона {метка}",
                    component=сторона.ссылка,
                    semi_product=f"{_топология(с, сост)} (экран припаян, ст. {метка})",
                    depends_on=list(концы),
                ).position
            )
        концы = экран or концы
    else:
        концы = [
            добавить(
                code=КОД_ОПРЕССОВКА_ВТУЛКИ,
                name="Опрессовка втулки экрана" + (f" ×{концов}" if концов > 1 else ""),
                semi_product=f"{_топология(с, сост)} (экран опрессован)",
                count=концов,
                depends_on=list(концы),
            ).position
        ]

    # ── 5. Усадка ───────────────────────────────────────────────────────
    усадка = добавить(
        code=КОД_УСАДКА,
        name="Усадка термоусадки" + (f" ×{концов}" if концов > 1 else ""),
        semi_product=f"{_топология(с, сост)} (ТУТ усажен)",
        count=концов,
        depends_on=list(концы),
    )

    # ── 6. Крышки угловых разъёмов ──────────────────────────────────────
    #
    # Последними: крышка закрывает узел целиком, и поставленная раньше
    # она перекрывает доступ к термоусадке. Один лист на ТИП крышки,
    # время — по числу угловых сторон с такой крышкой.
    крышки: dict[str, int] = {}
    for сторона in (с.side_a, с.side_b):
        if сторона is None or not сторона.угловой or not сторона.cover:
            continue
        крышки[сторона.cover] = крышки.get(сторона.cover, 0) + 1

    for сторона in (с.side_a, с.side_b):
        if сторона is not None and сторона.угловой and not сторона.cover:
            предупреждения.append(
                f"Угловой разъём {сторона.ссылка}: крышка не указана — "
                "проверить, нужна ли она по чертежу"
            )

    for тип, код, подпись in (
        (КРЫШКА_ОБЖИМ, КОД_КРЫШКА_ОБЖИМ, "обжим"),
        (КРЫШКА_ВИНТ, КОД_КРЫШКА_ВИНТ, "винт"),
    ):
        сколько = крышки.get(тип)
        if not сколько:
            continue
        добавить(
            code=код,
            name=f"Монтаж крышки ({подпись})" + (f" ×{сколько}" if сколько > 1 else ""),
            count=сколько,
            semi_product=f"{_топология(с, сост)} (крышка установлена)",
            depends_on=[усадка.position],
        )

    return шаги, предупреждения
