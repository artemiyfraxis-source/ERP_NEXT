records = wires() if not dry else records

total = {"written": 0, "already": 0, "refused": 0, "missing": 0}
for row in PAYLOAD["prov"]:
    mark = row["mark"]
    record = records.get(cable_key(mark))
    if record is None:
        total["missing"] += 1
        print(f"   нет строки «{mark}»")
        continue
    edits = []
    for field, value in row["fields"].items():
        current = str(record.fields.get(field, "") or "")
        if current == value:
            total["already"] += 1
        elif current:
            total["refused"] += 1
            print(f"   отказ «{mark}», {field}: в ячейке «{current}» — не тронуто")
        else:
            edits.append(FieldEdit(field, "", value))
    strand = row.get("strand")
    if strand:
        current = str(record.fields.get(STRAND, "") or "")
        if current == strand["new"]:
            total["already"] += 1
        elif current != strand["old"]:
            total["refused"] += 1
            print(f"   отказ «{mark}», {STRAND}: в ячейке «{current}», ждали «{strand['old']}» — не тронуто")
        else:
            edits.append(FieldEdit(STRAND, strand["old"], strand["new"]))
    if edits and not dry:
        try:
            edit_record(EditRecordCommand(record.id, tuple(edits), ACTOR, now), factory())
        except Exception as error:  # noqa: BLE001 — one record refused, the rest go on
            total["refused"] += len(edits)
            print(f"   отказ «{mark}»: {error}")
            continue
    total["written"] += len(edits)
print("ИТОГО", total, "(проверка, ничего не записано)" if dry else "(записано)")
