if mode not in ("dry", "apply"):
    raise SystemExit("режим: dry | apply")
dry = mode == "dry"
factory = build_references_uow_factory(build_engine(os.environ["ERP_DATABASE_URL"]))
now = moscow_now()


def wires():
    with factory() as uow:
        return {cable_key(r.fields.get("Марка") or r.display_text): r
                for r in uow.tech_operations.list(tab=TechOperationTab.WIRE, query="", limit=100_000)}


records = wires()
have = {name for record in records.values() for name in record.fields}
for name in PAYLOAD["columns"]:
    if name not in have:
        if dry:
            print(f"столбец «{name}» будет добавлен (apply)")
        else:
            add_column(ColumnCommand(TechOperationTab.WIRE, name, ACTOR, now), factory())
            print(f"столбец «{name}» добавлен")
records = wires() if not dry else records

total = {"written": 0, "already": 0, "refused": 0, "missing": 0}
for row in PAYLOAD["prov"]:
    mark = row["mark"]
    record = records.get(cable_key(mark))
    if record is None:
        total["missing"] += 1
        print(f"   нет строки «{mark}»")
        continue
    edits = []
    for field, value in row["fields"].items():
        current = str(record.fields.get(field, "") or "")
        if current == value:
            total["already"] += 1
        elif current:
            total["refused"] += 1
            print(f"   отказ «{mark}», {field}: в ячейке «{current}» — не тронуто")
        else:
            edits.append(FieldEdit(field, "", value))
    if edits and not dry:
        try:
            edit_record(EditRecordCommand(record.id, tuple(edits), ACTOR, now), factory())
        except Exception as error:  # noqa: BLE001 — one record refused, the rest go on
            total["refused"] += len(edits)
            print(f"   отказ «{mark}»: {error}")
            continue
    total["written"] += len(edits)
print("ИТОГО", total, "(проверка, ничего не записано)" if dry else "(записано)")
