    current = index.get(cable_key(cable))
    if item["new"] and current is not None:
        total["dia_skipped"] += 1
        print(f"   D: пропуск «{cable}»: строка уже есть ({current.fields.get('Кабель')})")
        continue
    if not item["new"]:
        if current is None:
            total["dia_skipped"] += 1
            print(f"   D: пропуск «{cable}»: нет строки")
            continue
        stale = [k for k in ("D1", "D2", "D3") if str(current.fields.get(k, "")).strip() != str(item["old"].get(k, "")).strip()]
        if stale:
            total["dia_refused"] += 1
            print(f"   D: отказ «{cable}»: {', '.join(stale)} уже другое значение")
            continue
    if not dry:
        try:
            set_coax_diameters(SetCoaxDiametersCommand(cable, current.id if current else None, dict(item["old"]),
                                                       dict(item["value"]), ACTOR, now), factory())
        except Exception as error:  # noqa: BLE001
            total["dia_refused"] += 1
            print(f"   D: отказ «{cable}»: {error}")
            continue
        index = dia_rows()
    total["dia_created" if item["new"] else "dia_filled"] += 1
