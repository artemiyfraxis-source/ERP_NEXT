def fold(value) -> str:
    return " ".join(str(value or "").casefold().split())


def article_of(record) -> str:
    return str(record.fields.get("coaxArticle") or record.fields.get("Артикул") or "").strip()


def cable_of(record) -> str:
    return str(record.fields.get("coaxWire") or record.fields.get("Провод") or "").strip()


def load(uow):
    return uow.tech_operations.list(tab=TechOperationTab.COAX, query="", limit=100_000)


def find_row(records, item):
    """Строка по естественному ключу (артикул без регистра + cable_key кабеля); id из выгрузки прода — сверка."""
    key = (fold(item["article"]), cable_key(item["cable"]))
    found = [r for r in records if (fold(article_of(r)), cable_key(cable_of(r))) == key]
    if len(found) != 1:
        return None
    return found[0]


def plan_row(record, edits):
    """(к записи, уже так, отказ): ячейка уже равна новому — «уже так»; не равна ни старому, ни новому — отказ."""
    todo, done, refused = [], [], []
    for field, old, new in edits:
        have = str(record.fields.get(field, "") or "")
        if have == new:
            done.append((field, old, new))
        elif have != old:
            refused.append((field, old, new, have))
        else:
            todo.append((field, old, new))
    return todo, done, refused


def write_row(uow, record_id, todo, now, commit):
    for i in range(0, len(todo), MAX_ROW_EDITS):
        chunk = tuple(FieldEdit(f, o, n) for f, o, n in todo[i:i + MAX_ROW_EDITS])
        record, updated = _edit_in(record_id, chunk, now, uow)
        _same_article(updated, chunk, now, uow)
        if commit:
            _audit("references.tech_record_edited", ACTOR, now, {
                "record_id": str(record.id), "tab": record.tab.value, "fields": [e.field for e in chunk],
                "reason": REASON}, uow)


def main(mode: str) -> int:
    factory = build_references_uow_factory(build_engine(os.environ["ERP_DATABASE_URL"]))
    dry = mode == "dry"
    now = moscow_now()
    with factory() as uow:
        records = load(uow)
    before = {r.id: dict(r.fields) for r in records}
    print(f"строк БД.КОАКС: {len(records)}; строк в плане: {len(PAYLOAD)}")
    written, same_already, problems = 0, 0, 0
    with factory() as uow:  # одна транзакция: dry — откатывается, apply — фиксируется целиком
        for item in PAYLOAD:
            row = find_row(load(uow), item)
            head = f"«{item['article']}» × {item['cable']}"
            if row is None:
                problems += 1
                print(f"   ОТКАЗ: строка не найдена по ключу артикул + кабель — {head}")
                continue
            todo, done, refused = plan_row(row, item["edits"])
            if refused:
                problems += 1
                for field, old, new, have in refused:
                    print(f"   ОТКАЗ: {head}: {field} — сейчас «{have[:80]}», ждали «{old[:80]}»")
                continue
            if not todo:
                same_already += 1
                continue
            print(f"   к записи: {head}: " + ", ".join(f for f, _, _ in todo if f != "Источник данных"))
            try:
                write_row(uow, row.id, todo, now, commit=not dry)
                written += len(todo)
            except (StaleRecordError, ReferenceValidationError, LookupError) as error:
                problems += 1
                print(f"   ОТКАЗ записи {head}: {error}")
        if problems:
            print("ЕСТЬ ОТКАЗЫ — ничего не записано" if not dry else "ЕСТЬ ОТКАЗЫ")
        elif not dry:
            uow.commit()
    if not dry and not problems:
        with factory() as uow:
            after = {r.id: r for r in load(uow)}
        log = [["вид", "id", "артикул", "кабель", "поле", "было", "стало"]]
        for rid, rec in after.items():
            was = before.get(rid)
            if was is None:
                continue
            for name in sorted(set(rec.fields) | set(was)):
                if str(was.get(name, "")) != str(rec.fields.get(name, "")) and not is_coax_cable_column(name) \
                        and name not in schema_keys("coax"):
                    log.append(["ячейка", str(rid), article_of(rec), cable_of(rec), name, str(was.get(name, "")),
                                str(rec.fields.get(name, ""))])
        print("\n== CSV-журнал отката ==")
        buffer = io.StringIO()
        csv.writer(buffer, lineterminator="\n").writerows(log)
        print(buffer.getvalue())
    summary = {"строк": len(PAYLOAD), "ячеек к записи/записано": written, "уже так": same_already, "проблем": problems}
    print("ИТОГО", json.dumps(summary, ensure_ascii=False), "(проверка, ничего не записано)" if dry else
          ("(записано)" if not problems else "(НЕ записано)"))
    return 1 if problems else 0


def rollback(path: str) -> int:
    factory = build_references_uow_factory(build_engine(os.environ["ERP_DATABASE_URL"]))
    now = moscow_now()
    problems = 0
    with open(path, encoding="utf-8", newline="") as handle:
        rows = [r for r in csv.DictReader(handle) if r["вид"] == "ячейка"]
    for row in reversed(rows):
        with factory() as uow:
            try:
                record, _ = _edit_in(UUID(row["id"]), (FieldEdit(row["поле"], row["стало"], row["было"]),), now, uow)
                _audit("references.tech_record_edited", ACTOR, now, {
                    "record_id": str(record.id), "tab": record.tab.value, "fields": [row["поле"]],
                    "reason": "откат: " + REASON}, uow)
                uow.commit()
            except (StaleRecordError, ReferenceValidationError, LookupError) as error:
                problems += 1
                print(f"   отказ: {row['артикул']} {row['поле']}: {error}")
    print("ИТОГО откат, ячеек:", len(rows), "проблем:", problems)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    run_mode = (sys.argv[1] if len(sys.argv) > 1 else "dry").strip()
    if run_mode not in ("dry", "apply", "rollback"):
        raise SystemExit("режим: dry | apply | rollback <csv>")
    raise SystemExit(rollback(sys.argv[2]) if run_mode == "rollback" else main(run_mode))
