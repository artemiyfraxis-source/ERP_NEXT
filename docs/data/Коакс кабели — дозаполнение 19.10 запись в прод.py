total = {"столбцов добавить": 0, "к записи": 0, "D-строк новых": 0, "уже так": 0, "отказ": 0}


def wires():
    with factory() as uow:
        return {cable_key(r.fields.get("Марка") or r.display_text): r
                for r in uow.tech_operations.list(tab=TechOperationTab.WIRE, query="", limit=100_000)}


records = wires()
marks = sorted({mark for mark, _, _ in PAYLOAD["prov"]} | {mark for mark, _ in PAYLOAD["dia"]})
missing = [mark for mark in marks if cable_key(mark) not in records]
if missing:
    print("СТОП — нет строк в БД.ПРОВ (ничего не записано):", ", ".join(missing))
    raise SystemExit(1)

with factory() as uow:
    have_columns = set(custom_columns(TechOperationTab.WIRE, uow))
for name in PAYLOAD["columns"]:
    if name in have_columns:
        continue
    total["столбцов добавить"] += 1
    if dry:
        print(f"столбец «{name}» будет добавлен (apply)")
    else:
        count = add_column(ColumnCommand(TechOperationTab.WIRE, name, ACTOR, now), factory())
        print(f"столбец «{name}» добавлен: {count} записей")
if not dry:
    records = wires()

print("== БД.ПРОВ")
by_mark = defaultdict(list)
for mark, field, value in PAYLOAD["prov"]:
    by_mark[mark].append((field, value))
base_rows = []  # sheet columns of БД.ПРОВ: the load by «Марка» (an older row may lack the key in its fields)
for mark, cells in by_mark.items():
    record = records[cable_key(mark)]
    write, base, refused = [], {}, []
    for field, value in cells:
        current = str(record.fields.get(field, "") or "").strip()
        if current == value:
            total["уже так"] += 1
        elif current == "":
            if field in BASE_COLUMNS[TechOperationTab.WIRE]:
                base[field] = value
            else:
                write.append(FieldEdit(field, "", value))
        else:
            refused.append(f"{field}: в ячейке «{current[:60]}», писали «{value}»")
    if refused:
        total["отказ"] += len(refused)
        print(f"   отказ «{mark}» (заполнено): " + "; ".join(refused))
    if base:
        base_rows.append(ImportRowIn(fields={"Марка": record.fields.get("Марка") or mark, **base},
                                     old={field: "" for field in base}))
    if not write:
        continue
    if not dry:
        try:
            edit_record(EditRecordCommand(record.id, tuple(write), ACTOR, now), factory())
        except (StaleRecordError, ReferenceValidationError) as error:
            total["отказ"] += len(write)
            print(f"   отказ «{mark}»: {error}")
            continue
    total["к записи"] += len(write)
if base_rows:
    def load(dry_run):
        return import_rows("prov", factory(), base_rows, ACTOR, now, dry_run=dry_run, source="erp").model_dump()
    data = load(True)
    if data["created"]:
        print("СТОП — загрузка по «Марке» завела бы новые строки, столбцы БД.ПРОВ не записаны:", data["created"])
        raise SystemExit(1)
    if not dry:
        data = load(False)
    cells = sum(len(row.fields) - 1 for row in base_rows)
    written = sum(len(item["changes"]) for item in data["updated"])
    refused_keys = {cable_key(item["key"]) for item in data["refused"]}
    refused_cells = sum(len(row.fields) - 1 for row in base_rows if cable_key(row.fields["Марка"]) in refused_keys)
    for item in data["refused"]:
        print(f"   отказ (загрузка) «{item['key']}»: {item['reason']}")
    total["к записи"] += written
    total["отказ"] += refused_cells
    if written + refused_cells != cells:
        print(f"   ВНИМАНИЕ: ячеек {cells}, записано {written}, отказ {refused_cells} — не сходится")
    print(f"   столбцы БД.ПРОВ загрузкой: строк {len(base_rows)}, ячеек {cells}; "
          f"{'к записи' if dry else 'записано'} {written}, отказ {refused_cells}")

