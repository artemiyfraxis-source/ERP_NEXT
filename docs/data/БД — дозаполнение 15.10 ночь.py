def run(table, rows, label, *, may_create=False):
    def call(dry_run):
        return import_rows(table, factory(), [ImportRowIn(fields=r["fields"], old=r["old"]) for r in rows], ACTOR, now,
                           dry_run=dry_run, source="erp").model_dump()

    data = call(True)
    # a fill must find its row — never create a half row from a fill: the whole group stops
    if data["created"] and not may_create:
        print(f"== {label}: СТОП — строки не найдены, ничего не записано: {data['created']}")
        return data
    if not dry:
        data = call(False)
    print(f"== {label}: строк {len(rows)} → создано {len(data['created'])}, обновлено {len(data['updated'])}, "
          f"без изменений {data['unchanged']}, отказ {len(data['refused'])}")
    for item in data["refused"]:
        print("   отказ:", item)
    return data


