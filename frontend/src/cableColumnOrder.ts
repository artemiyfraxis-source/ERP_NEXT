/** Столбцы списка: в порядке групп, видны «нужные» списка и те, что `alsoShown` (новый свой столбец владельца, «Почему
    здесь» при строках, перенесённых вручную); остальные — скрыты, в «Колонках». */
export function arrangeCableColumns<T>(kind: CableKind, columns: DataColumn<T>[], alsoShown: (key: string) => boolean = () => false): DataColumn<T>[] {
  const shown = CABLE_DEFAULT_SHOWN[kind];
  return sortCableColumns(columns).map((column) => ({ ...column, hidden: !(shown.has(column.key) || alsoShown(column.key)) }));
}
