const RANK = new Map(CABLE_COLUMN_ORDER.map((key, index) => [key, index]));
const UNKNOWN_RANK = CABLE_COLUMN_ORDER.indexOf(SUPPLY[0]) - 0.5;

// Убранные 25.10.2026: места в порядке нет, а старый сервер, приславший такой свой столбец, его не покажет.
const REMOVED = new Set(["Цвета", "Дата цены", "Цена посл., ₽/м без НДС", "Закупок", "Источник данных", "Ток, А", "Изоляция"]);
/** Знает ли общий порядок этот столбец (свой столбец владельца с другим именем — нет). */
export const knownCableColumn = (key: string) => RANK.has(key) || REMOVED.has(key);

/** Столбцы в порядке групп; незнакомые — перед поставкой, между собой — как пришли. */
export function sortCableColumns<T>(columns: DataColumn<T>[]): DataColumn<T>[] {
  return columns.map((column, index) => ({ column, index }))
    .sort((a, b) => (RANK.get(a.column.key) ?? UNKNOWN_RANK) - (RANK.get(b.column.key) ?? UNKNOWN_RANK) || a.index - b.index)
    .map((item) => item.column);
}

