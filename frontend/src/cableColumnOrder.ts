/** Столбцы списка в порядке групп: только столбцы списка (`CABLE_DEFAULT_SHOWN`) и те, что `alsoShown` (свой столбец
    владельца, которого порядок не знает); остального в таблице нет вовсе — ни в «Колонках», ни в «Показать все». */
export function arrangeCableColumns<T>(kind: CableKind, columns: DataColumn<T>[], alsoShown: (key: string) => boolean = () => false): DataColumn<T>[] {
  const shown = CABLE_DEFAULT_SHOWN[kind];
  return sortCableColumns(columns.filter((column) => shown.has(column.key) || alsoShown(column.key))).map((column) => ({ ...column, hidden: false }));
}
