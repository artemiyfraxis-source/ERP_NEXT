/** Ключ сравнения: регистр, «ё/е» и лишние пробелы не важны. */
function keyOf(word: string) {
  return word.trim().replace(/\s+/g, " ").replace(/ё/g, "е").replace(/Ё/g, "Е").toLowerCase();
}

const TONE_BY_KEY = new Map<string, Tone>();
for (const tone of TONES) for (const word of WORDS[tone]) TONE_BY_KEY.set(keyOf(word), tone);
// Регистр не различает «Пауза» и «ПАУЗА» — оба одного тона; ключ слова, записанного дважды, один.
const LABEL_BY_KEY = new Map(Object.entries(LEGACY_LABELS).map(([legacy, label]) => [keyOf(legacy), label]));

/** Все слова словаря (для легенды и проверки покрытия). */
export const STATUS_WORDS: readonly string[] = TONES.flatMap((tone) => WORDS[tone]);

/** Слово для экрана: слово листа → слово ERP; остальное — как пришло, без лишних пробелов. */
export function statusLabel(status: string | null | undefined): string {
  const word = String(status ?? "").trim().replace(/\s+/g, " ");
  return LABEL_BY_KEY.get(keyOf(word)) ?? word;
}

/** Тон статуса; незнакомое слово — нейтральный. */
export function statusTone(status: string | null | undefined): Tone {
  const label = statusLabel(status);
  return TONE_BY_KEY.get(keyOf(label)) ?? "neutral";
}

/** Слово есть в словаре (само или через слово ERP). */
export function isKnownStatus(status: string | null | undefined): boolean {
  return TONE_BY_KEY.has(keyOf(statusLabel(status)));
}

/** Тон срока по дням до него: просрочен — danger, 3 дня и меньше — warning, иначе — neutral (красный = горит). */
export function deadlineTone(daysLeft: number | null | undefined): Tone {
  if (daysLeft === null || daysLeft === undefined || !Number.isFinite(daysLeft)) return "neutral";
  if (daysLeft < 0) return "danger";
  if (daysLeft <= 3) return "warning";
  return "neutral";
}
